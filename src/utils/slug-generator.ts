type GenerateSlugParams = {
  /** The text to convert into a URL-friendly slug */
  text: string | undefined
  /** Whether to append UUID suffix to the generated slug (default: false) */
  withId?: boolean
}

/**
 * Generates a URL-friendly slug from text with optional UUID suffix
 *
 * This function performs comprehensive text normalization:
 * - Converts to lowercase
 * - Removes accents and diacritics
 * - Replaces spaces with hyphens
 * - Removes special characters (keeps only alphanumeric and hyphens)
 * - Removes consecutive hyphens
 * - Trims leading/trailing hyphens
 * - Optionally appends UUID suffix for uniqueness
 *
 * @param params - Configuration object for slug generation
 * @param params.text - The input text to slugify (required, non-empty)
 * @param params.uuid - UUID to append when withId is true (required if withId=true)
 * @param params.withId - Flag to append UUID suffix (default: false)
 *
 * @returns URL-friendly slug string, optionally with UUID suffix
 *
 * @throws {Error} If text is not a string or is empty/whitespace only
 * @throws {Error} If generated slug is empty (input contains only special characters)
 * @throws {Error} If withId is true but uuid is not provided
 *
 * @example
 * Basic usage
 * generateSlug({ text: "Hello World!" })
 * Returns: "hello-world"
 *
 * @example
 * With accents and special characters
 * generateSlug({ text: "Café & Restaurant #1" })
 * Returns: "cafe-restaurant-1"
 *
 * @example
 * With UUID suffix
 * generateSlug({
 *   text: "My Article",
 *   uuid: "123e4567-e89b-12d3-a456-426614174000",
 *   withId: true
 * })
 * Returns: "my-article-426614174000"
 *
 * @example
 * Handles multiple spaces and consecutive hyphens
 * generateSlug({ text: "Hello    World---Test" })
 * Returns: "hello-world-test"
 *
 * @example
 * Error: Empty input
 * generateSlug({ text: "   " })
 * Throws: "Input string cannot be empty or contain only whitespace"
 *
 * @example
 * Error: Only special characters
 * generateSlug({ text: "!@#$%^&*()" })
 * Throws: "Generated slug is empty. Input may contain only special characters."
 *
 * @example
 * Error: Missing UUID when withId is true
 * generateSlug({ text: "Article", withId: true })
 * Throws: "UUID is required when withId = true"
 */
export const generateSlug = ({
  text,
  withId = true,
}: GenerateSlugParams): string => {
  // Validate input is a non-empty string
  if (!text || typeof text !== 'string') {
    throw new Error(
      `Input must be a non-empty string. Received: ${typeof text === 'string' ? '"' + text + '"' : typeof text}`,
    )
  }

  // Check for whitespace-only input
  if (text.trim().length === 0) {
    throw new Error('Input string cannot be empty or contain only whitespace')
  }

  // Generate slug with normalization pipeline
  const slug = text
    .toLowerCase() // Convert to lowercase
    .normalize('NFD') // Normalize unicode characters
    .replace(/[\u0300-\u036f]/g, '') // Remove diacritics/accents
    .replace(/\s+/g, '-') // Replace spaces with hyphens
    .replace(/[^\w-]+/g, '') // Remove non-alphanumeric except hyphens
    .replace(/-{2,}/g, '-') // Replace consecutive hyphens with single hyphen
    .replace(/^-+/, '') // Remove leading hyphens
    .replace(/-+$/, '') // Remove trailing hyphens

  // Validate slug is not empty after normalization
  if (slug.length === 0) {
    throw new Error(
      'Generated slug is empty. Input may contain only special characters.',
    )
  }

  if (withId) {
    const uuid = crypto.randomUUID()

    // Extract first segment of UUID (before first hyphen) or use entire UUID
    const uuidPrefix = uuid.includes('-')
      ? uuid.substring(0, uuid.indexOf('-'))
      : uuid

    return `${slug}-${uuidPrefix}`
  }

  return slug
}

type ExtractSlugIdParams = {
  /** The slug to extract the ID/UUID prefix from */
  slug: string | undefined
}

/**
 * Extracts the UUID prefix (ID) that was appended at the end of a slug
 * generated by `generateSlug({ ..., withId: true })`.
 *
 * Assumes the slug's last segment (after the final hyphen) is the
 * 8-character hexadecimal UUID prefix, e.g. `title-baru-f062fca0`.
 *
 * @param params - Configuration object
 * @param params.slug - The slug to extract the ID from (required, non-empty)
 *
 * @returns The extracted 8-character UUID prefix
 *
 * @throws {Error} If slug is not a string or is empty/whitespace only
 * @throws {Error} If slug has no hyphen (no ID segment to extract)
 * @throws {Error} If the last segment is not a valid 8-char hex string
 *
 * @example
 * extractSlugId({ slug: "title-baru-f062fca0" })
 * Returns: "f062fca0"
 *
 * @example
 * extractSlugId({ slug: "hello-world" })
 * Throws: "Extracted segment is not a valid UUID prefix..."
 *
 * @example
 * extractSlugId({ slug: "" })
 * Throws: "Input must be a non-empty string..."
 */
export const extractSlugId = ({ slug }: ExtractSlugIdParams): string => {
  // Validate input is a non-empty string
  if (!slug || typeof slug !== 'string') {
    throw new Error(
      `Input must be a non-empty string. Received: ${typeof slug === 'string' ? '"' + slug + '"' : typeof slug}`,
    )
  }

  // Check for whitespace-only input
  if (slug.trim().length === 0) {
    throw new Error('Input string cannot be empty or contain only whitespace')
  }

  const lastHyphenIndex = slug.lastIndexOf('-')

  // No hyphen means there's no separate ID segment to extract
  if (lastHyphenIndex === -1) {
    throw new Error('Slug does not contain an ID segment (no hyphen found)')
  }

  const id = slug.substring(lastHyphenIndex + 1)

  // Validate the extracted segment looks like an 8-char hex UUID prefix
  // (matches the first segment of a v4 UUID, e.g. "f062fca0" from
  // "f062fca0-e89b-12d3-a456-426614174000")
  if (!/^[0-9a-f]{8}$/i.test(id)) {
    throw new Error(
      `Extracted segment is not a valid UUID prefix. Received: "${id}"`,
    )
  }

  return id
}

/**
 * Non-throwing variant of {@link extractSlugId}.
 * Returns `null` instead of throwing when the ID cannot be extracted —
 * useful when the slug's origin/format isn't guaranteed.
 *
 * @example
 * tryExtractSlugId({ slug: "title-baru-f062fca0" }) // "f062fca0"
 * tryExtractSlugId({ slug: "no-id-here" })           // null
 */
export const tryExtractSlugId = (
  params: ExtractSlugIdParams,
): string | null => {
  try {
    return extractSlugId(params)
  } catch {
    return null
  }
}
